// Build the local variant public/local.html from public/index.html
//
//   node scripts/build-local.mjs
//
// The local variant has no built-in product database: devices, views, connectors, SYSBOXX, rack parts and weights
// are loaded from the Stagecraft Library (https://library.stagecraft.solutions/api/v1/rackmanufaktur/*.json),
// cached in the browser and stored per project in the project file (state.lib), so projects open offline.
// Newer library states show a refresh icon on the device and in the "Library" window.
//
// Sources: scripts/local/loader.js (runs first, fetches and caches), scripts/local/client.js (injected into the
// app), scripts/local/local.css. public/local.html is generated – never edit it by hand.
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('..', import.meta.url);
const rd = f => readFileSync(new URL(f, ROOT), 'utf8');
let src = rd('public/index.html');
const loader = rd('scripts/local/loader.js'), client = rd('scripts/local/client.js'), css = rd('scripts/local/local.css');

function once(label, find, repl) {
  const n = typeof find === 'string' ? src.split(find).length - 1 : (src.match(new RegExp(find.source, find.flags.includes('g') ? find.flags : find.flags + 'g')) || []).length;
  if (n !== 1) throw new Error(`${label}: anchor found ${n}× in public/index.html (expected once) – update scripts/build-local.mjs`);
  src = src.replace(find, typeof repl === 'function' ? repl : () => repl);
}

// 1. data blocks → filled by the loader
const VAR = { DEVDB: 'DEVDB', KG: 'KG', EXACT: 'EXACT_JSON', CTYPES: 'CTYPES', CON: 'CON', SBX: 'SBX', PARTS: 'PARTS' };
for (const [k, v] of Object.entries(VAR)) {
  once(`data block ${k}`, new RegExp(`/\\* DATA:${k} \\*/[\\s\\S]*?/\\* /DATA:${k} \\*/`), `/* DATA:${k} – local variant: from the Stagecraft Library */ const ${v} = window.__RM.${k === 'EXACT' ? 'EXACT' : k};`);
}
// 2. code views that extend library devices: tolerate devices that are not loaded (offline, removed)
const tm = src.match(/^EXACT\.(\w+)\.r = /gm) || [];
if (!tm.length) throw new Error('code views EXACT.<key>.r = … not found');
src = src.replace(/^EXACT\.(\w+)\.r = /gm, (m, k) => `(EXACT.${k} = EXACT.${k} || {}).r = `);
// 3. the app waits for the data: the loader starts it
once('app script', '<script>\n(() => {\n\'use strict\';', '<script type="text/plain" id="rmApp">\n(() => {\n\'use strict\';');
once('app start', '\nrender();\nLIB.init();\n})();\n</script>', `\n${client}\nrender();\nLIB.init();\n})();\n</script>\n<script>\n${loader}</script>`);
// 4. header chip, window, styles
once('header', '<span id="folderTxt">Kein Projektordner</span></button>', m => m + '\n    <button type="button" class="btn sm libchip" id="btnLib" data-st="wait" aria-haspopup="dialog"><span class="dot" aria-hidden="true"></span><span id="libTxt">Library</span><span class="count" id="libCount"></span></button>');
once('dialog', '<div class="toast" id="toast" role="status"></div>', m => `<dialog class="add lib" id="libDlg" aria-labelledby="libTitleH">
  <div class="dlg-head"><h2 id="libTitleH">Stagecraft Library</h2><button type="button" class="dlg-close" data-libact="close" aria-label="Schließen">×</button></div>
  <div class="dlg-body" id="libBody"></div>
</dialog>
${m}`);
once('styles', /<\/style>(?![\s\S]*<\/style>)/, `${css}</style>`);
src = src.replace(/^<!doctype html>/i, m => `${m}\n<!-- Generated by scripts/build-local.mjs from public/index.html – do not edit. Local variant: product data from the Stagecraft Library. -->`);

writeFileSync(new URL('public/local.html', ROOT), src);
console.log(`Built public/local.html (${Math.round(src.length / 1024)} KB, ${tm.length} code views made tolerant)`);
